    /// 图标画布边长（pt），2048 画布等比缩入，主体字形约占宽 15pt。
    static let iconSide: CGFloat = 18

    static func makeIcon() -> NSImage {
        let image = NSImage(size: NSSize(width: iconSide, height: iconSide), flipped: false) { rect in
            let path = NSBezierPath()
            path.windingRule = .nonZero
            let scale = rect.width / 2048
            for segment in segments {
                switch segment {
                case let .move(x, y):
                    path.move(to: NSPoint(x: x * scale, y: y * scale))
                case let .curve(x1, y1, x2, y2, x, y):
                    path.curve(
                        to: NSPoint(x: x * scale, y: y * scale),
                        controlPoint1: NSPoint(x: x1 * scale, y: y1 * scale),
                        controlPoint2: NSPoint(x: x2 * scale, y: y2 * scale))
                case .close:
                    path.close()
                }
            }
            NSColor.black.setFill()
            path.fill()
            return true
        }
        image.isTemplate = true
        return image
    }
